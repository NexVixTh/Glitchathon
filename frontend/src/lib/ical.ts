/**
 * SyncUp AI - RFC 5545 iCalendar (.ics) Exporter
 * Generates and triggers download of standard .ics calendar files compatible with
 * Google Calendar, Apple Calendar, Microsoft Outlook, and mobile calendar apps.
 */

import { ScheduleResponse, StudyBlock } from '../types';

/**
 * Formats a Date object or date string into standard iCalendar UTC timestamp: YYYYMMDDTHHMMSSZ
 */
function formatICalDate(date: Date): string {
  const pad = (n: number) => (n < 10 ? `0${n}` : `${n}`);
  return (
    date.getUTCFullYear() +
    pad(date.getUTCMonth() + 1) +
    pad(date.getUTCDate()) +
    'T' +
    pad(date.getUTCHours()) +
    pad(date.getUTCMinutes()) +
    pad(date.getUTCSeconds()) +
    'Z'
  );
}

/**
 * Escapes special characters for RFC 5545 compliance (commas, semicolons, backslashes, newlines).
 */
function escapeICalText(text: string): string {
  if (!text) return '';
  return text
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n');
}

/**
 * Computes start and end timestamps for a study block on its scheduled date.
 * Default study start: 10:00 AM local time.
 */
function calculateEventTimes(dateStr: string, allocatedHours: number): { start: Date; end: Date } {
  // Parse YYYY-MM-DD
  const parts = dateStr.split('-');
  const year = parseInt(parts[0], 10) || new Date().getFullYear();
  const month = parseInt(parts[1], 10) - 1 || 0;
  const day = parseInt(parts[2], 10) || 1;

  // Set default study start at 10:00 AM
  const start = new Date(year, month, day, 10, 0, 0);

  // Calculate duration in minutes (e.g. 2.5 hours = 150 minutes)
  const durationMinutes = Math.max(Math.round(allocatedHours * 60), 30);
  const end = new Date(start.getTime() + durationMinutes * 60 * 1000);

  return { start, end };
}

/**
 * Converts a ScheduleResponse into a valid RFC 5545 .ics file and triggers a client-side download.
 *
 * @param schedule - The current ScheduleResponse object.
 * @param courseTitle - The course or syllabus title.
 */
export function exportScheduleToICS(schedule: ScheduleResponse, courseTitle: string = 'Course Syllabus'): void {
  if (!schedule || !schedule.studyBlocks || schedule.studyBlocks.length === 0) {
    throw new Error('No study schedule blocks available to export.');
  }

  const now = new Date();
  const dtStamp = formatICalDate(now);
  const sanitizedCourseTitle = courseTitle.trim() || 'SyncUp Study Schedule';

  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//SyncUp AI//Semester Copilot v1.0//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:${escapeICalText(`SyncUp - ${sanitizedCourseTitle}`)}`,
    'X-WR-TIMEZONE:UTC',
    'X-WR-CALDESC:Personalized semester study roadmap with adaptive workload pacing and active recall generated by SyncUp AI.',
  ];

  schedule.studyBlocks.forEach((block: StudyBlock, index: number) => {
    const { start, end } = calculateEventTimes(block.date, block.allocatedHours);
    const uid = `syncup-${block.id || index}-${start.getTime()}@syncup.ai`;

    let prefix = '📚 Study:';
    if (block.isExamDay) {
      prefix = '🚨 EXAM:';
    } else if (block.isReviewDay) {
      prefix = '🔄 Review:';
    }

    const summary = `${prefix} ${block.topic} (${sanitizedCourseTitle})`;
    const description = [
      `Task: ${block.taskDescription}`,
      `Topic: ${block.topic}`,
      `Course: ${sanitizedCourseTitle}`,
      `Allocated Time: ${block.allocatedHours} hours`,
      `Status: ${block.completed ? 'Completed' : 'Pending'}`,
      'Powered by SyncUp AI Semester Copilot',
    ].join('\n');

    lines.push('BEGIN:VEVENT');
    lines.push(`UID:${uid}`);
    lines.push(`DTSTAMP:${dtStamp}`);
    lines.push(`DTSTART:${formatICalDate(start)}`);
    lines.push(`DTEND:${formatICalDate(end)}`);
    lines.push(`SUMMARY:${escapeICalText(summary)}`);
    lines.push(`DESCRIPTION:${escapeICalText(description)}`);
    lines.push('STATUS:CONFIRMED');
    lines.push(`CATEGORIES:${block.isExamDay ? 'EXAM,EDUCATION' : 'STUDY,EDUCATION,SYNCUP'}`);
    lines.push('TRANSP:OPAQUE');
    lines.push('END:VEVENT');
  });

  lines.push('END:VCALENDAR');

  // Join lines with RFC 5545 standard CRLF line break
  const icsContent = lines.join('\r\n');

  // Trigger browser download via Blob
  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', 'syncup-schedule.ics');
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
